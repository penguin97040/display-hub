/// Every vector, with fresh throwaway keys, and each expectation worked out by the reference. Fails
/// if the reference disagrees with what the document says a case must come to.
pub fn generate() -> Result<Vec<Vector>, String> {
    let k = Keys::generate()?;
    let keys = k.table();
    let vector = |name: &str, cases: Vec<u32>, description: &str, test: Test| Vector {
        format: FORMAT.into(),
        version: VERSION,
        name: name.into(),
        cases,
        description: description.into(),
        keys: keys.clone(),
        test,
    };
    let mut out = Vec::new();
    for (n, p) in package_cases(&k).into_iter().enumerate() {
        let v = reference(&vector(
            &p.name,
            p.cases,
            p.description,
            Test::Package {
                display: p.display,
                offer: Offer {
                    offer_id: offer_id(1000 + n as u32),
                    size: p.offer_size,
                },
                response: Response {
                    content_length: p.content_length,
                    body_hex: hex::encode(&p.body),
                    after_body: p.after.into(),
                },
                expect: placeholder_package_expect(),
            },
        ))?;
        if let Test::Package { expect, .. } = &v.test {
            if expect.state != p.intended.state || expect.reason.as_deref() != p.intended.reason {
                return Err(format!(
                    "{}: the document says {} {:?}, the reference gives {} {:?}",
                    p.name, p.intended.state, p.intended.reason, expect.state, expect.reason
                ));
            }
        }
        out.push(v);
    }
    for c in offer_cases() {
        let v = reference(&vector(
            c.name,
            c.cases,
            c.description,
            Test::Offer {
                before: c.before,
                events: c.events,
                expect: OfferExpect {
                    actions: Vec::new(),
                    saves: 0,
                    after: BudgetState {
                        attempts_left: 0,
                        credit_hours: 0,
                        last_offer_id: None,
                    },
                },
            },
        ))?;
        if let Test::Offer { expect, .. } = &v.test {
            if expect.actions != c.actions {
                return Err(format!(
                    "{}: the document says {:?}, the reference gives {:?}",
                    c.name, c.actions, expect.actions
                ));
            }
        }
        out.push(v);
    }
    for c in trial_cases() {
        let strings = |v: &[&str]| v.iter().map(|s| s.to_string()).collect::<Vec<_>>();
        let v = reference(&vector(
            c.name,
            c.cases,
            c.description,
            Test::Trial {
                before: TrialBefore {
                    firmware_version: RUNNING.into(),
                    trusted_keys: strings(&["maker", "recovery"]),
                    security_floor: FLOOR,
                    update: TrialUpdate {
                        firmware_version: "1.2.0".into(),
                        security_counter: FLOOR + 1,
                        key_set: c.key_set.as_deref().map(strings),
                    },
                },
                trial: TrialEvents {
                    starts: c.starts,
                    check_ins: c
                        .check_ins
                        .iter()
                        .map(|(at, answer)| CheckInAt {
                            at_seconds: *at,
                            answer: answer.to_string(),
                        })
                        .collect(),
                    restart_at_seconds: c.restart_at,
                },
                expect: TrialExpect {
                    outcome: String::new(),
                    at_seconds: 0,
                    report: String::new(),
                    firmware_version: String::new(),
                    security_floor: 0,
                    trusted_keys: Vec::new(),
                },
            },
        ))?;
        if let Test::Trial { expect, .. } = &v.test {
            if expect.outcome != c.outcome {
                return Err(format!(
                    "{}: the document says {}, the reference gives {}",
                    c.name, c.outcome, expect.outcome
                ));
            }
        }
        out.push(v);
    }
    for (name, cases, description, before, floor, action, bundle, answer) in provision_cases() {
        let strings = |v: &[&str]| v.iter().map(|s| s.to_string()).collect::<Vec<_>>();
        let v = reference(&vector(
            name,
            cases,
            description,
            Test::Provision {
                before: KeysState {
                    trusted_keys: strings(&before),
                    security_floor: floor,
                },
                action: ProvisionAction {
                    action: action.into(),
                    bundle_firmware: bundle.map(|(keys, counter)| BundleKeys {
                        trusted_keys: strings(&keys),
                        security_counter: counter,
                    }),
                },
                expect: ProvisionExpect {
                    answer: None,
                    trusted_keys: Vec::new(),
                    security_floor: 0,
                },
            },
        ))?;
        if let Test::Provision { expect, .. } = &v.test {
            if expect.answer.as_deref() != answer {
                return Err(format!(
                    "{name}: the document says {answer:?}, the reference gives {:?}",
                    expect.answer
                ));
            }
        }
        out.push(v);
    }
    let mut seen = BTreeSet::new();
    if let Some(dup) = out.iter().find(|v| !seen.insert(v.name.clone())) {
        return Err(format!("two vectors are named {}", dup.name));
    }
    Ok(out)
}

fn files(dir: &Path) -> std::io::Result<Vec<std::path::PathBuf>> {
    let mut files: Vec<_> = std::fs::read_dir(dir)?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .collect();
    files.sort();
    Ok(files)
}

fn read(path: &Path) -> Result<Vector, String> {
    let bytes = std::fs::read(path).map_err(|e| e.to_string())?;
    let v: Vector = serde_json::from_slice(&bytes).map_err(|e| format!("not a vector ({e})"))?;
    if v.format != FORMAT || v.version != VERSION {
        return Err(format!("not a {FORMAT} version {VERSION} vector"));
    }
    Ok(v)
}

fn to_text(v: &Vector) -> String {
    let mut text = serde_json::to_string_pretty(v).expect("serialises");
    text.push('\n');
    text
}

/// Writes the vectors into `dir`. A committed vector that still matches a fresh generation (in
/// everything but its keys and package bytes) and still passes [`check`] is kept as it is, so
/// writing again changes nothing; any other is written afresh. Files for cases that no longer exist
/// are removed. Returns how many were written and how many kept.
pub fn write(dir: &Path) -> Result<(usize, usize), String> {
    let generated = generate()?;
    std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    let names: BTreeSet<String> = generated.iter().map(|v| format!("{}.json", v.name)).collect();
    for f in files(dir).map_err(|e| e.to_string())? {
        let name = f.file_name().unwrap_or_default().to_string_lossy().into_owned();
        if !names.contains(&name) {
            std::fs::remove_file(&f).map_err(|e| e.to_string())?;
        }
    }
    let (mut written, mut kept) = (0, 0);
    for v in &generated {
        let path = dir.join(format!("{}.json", v.name));
        let current = read(&path)
            .ok()
            .filter(|old| stable(old) == stable(v) && reference(old).is_ok_and(|r| &r == old));
        if current.is_some() {
            kept += 1;
        } else {
            std::fs::write(&path, to_text(v)).map_err(|e| e.to_string())?;
            written += 1;
        }
    }
    Ok((written, kept))
}

/// Checks every vector file in `dir` against this reference display. Returns the number of files
/// and the failures.
pub fn check(dir: &Path) -> std::io::Result<(usize, Vec<String>)> {
    let files = files(dir)?;
    let mut failures = Vec::new();
    for f in &files {
        let name = f.display().to_string();
        match read(f).and_then(|v| reference(&v).map(|r| (v, r))) {
            Err(e) => failures.push(format!("{name}: {e}")),
            Ok((v, r)) if r != v => failures.push(format!(
                "{name}: expected {:?}, the reference gives {:?}",
                v.test, r.test
            )),
            Ok(_) => {}
        }
    }
    Ok((files.len(), failures))
}

/// The reasons a display can report for `refused` and `failed`, for checking coverage.
pub fn reasons() -> impl Iterator<Item = &'static str> {
    ReportReason::ALL.into_iter().map(ReportReason::as_str)
}
