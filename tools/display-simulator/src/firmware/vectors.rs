struct Keys {
    maker: SigningKey,
    recovery: SigningKey,
    new: SigningKey,
    stranger: SigningKey,
    retired: SigningKey,
}

impl Keys {
    fn generate() -> Result<Self, String> {
        let one = || {
            SigningKey::generate()
                .map(|(k, _)| k)
                .map_err(|_| "couldn't make a throwaway key".to_string())
        };
        Ok(Self {
            maker: one()?,
            recovery: one()?,
            new: one()?,
            stranger: one()?,
            retired: one()?,
        })
    }

    fn table(&self) -> BTreeMap<String, String> {
        [
            ("maker", &self.maker),
            ("recovery", &self.recovery),
            ("new", &self.new),
            ("stranger", &self.stranger),
            ("retired", &self.retired),
        ]
        .into_iter()
        .map(|(n, k)| (n.to_string(), k.public_key().to_hex()))
        .collect()
    }

    fn hex(&self, name: &str) -> String {
        self.table()[name].clone()
    }
}

fn image() -> Vec<u8> {
    (0..IMAGE_LEN)
        .map(|i| (i as u8).wrapping_mul(37).wrapping_add(11))
        .collect()
}

fn sha256_hex(b: &[u8]) -> String {
    hex::encode(ring::digest::digest(&ring::digest::SHA256, b).as_ref())
}

/// A valid manifest for [`image`], for cases to change.
fn manifest(version: &str, counter: u32) -> Value {
    json!({
        "device_type": DEVICE_TYPE,
        "hardware_revisions": [HARDWARE],
        "firmware_version": version,
        "security_counter": counter,
        "image_size": IMAGE_LEN,
        "image_sha256": sha256_hex(&image()),
        "summary": format!("Release {version}"),
    })
}

/// A package's update form: the header, `manifest` exactly as given, and the image, signed by `key`
/// over the signed bytes (with the fixed text in front, unless `context` is false).
fn form(key: &SigningKey, manifest: &[u8], image: &[u8], context: bool) -> Vec<u8> {
    let len = u16::try_from(manifest.len()).expect("a short manifest");
    let prefix: [u8; SIGNED_HEADER_LEN] = signed_prefix(len, &key.public_key());
    let message = if context {
        firmware_package::signed_bytes(&prefix, manifest)
    } else {
        [prefix.as_slice(), manifest].concat()
    };
    let signature = key.sign(&message).expect("signing works");
    [prefix.as_slice(), &signature, manifest, image].concat()
}

fn signed(key: &SigningKey, manifest: &Value) -> Vec<u8> {
    form(
        key,
        &serde_json::to_vec(manifest).expect("serialises"),
        &image(),
        true,
    )
}

fn display(trusted: &[&str]) -> DisplayState {
    DisplayState {
        device_type: DEVICE_TYPE.into(),
        hardware_revision: HARDWARE.into(),
        firmware_version: RUNNING.into(),
        trusted_keys: trusted.iter().map(|s| s.to_string()).collect(),
        security_floor: FLOOR,
        slot_bytes: SLOT_BYTES,
    }
}

fn offer_id(n: u32) -> String {
    format!("{n:032x}")
}

/// What the document says a case must come to, which the reference must agree with.
struct Intended {
    state: &'static str,
    reason: Option<&'static str>,
}

const fn installed() -> Intended {
    Intended {
        state: "installed",
        reason: None,
    }
}

const fn refused(reason: &'static str) -> Intended {
    Intended {
        state: "refused",
        reason: Some(reason),
    }
}

const fn failed(reason: &'static str) -> Intended {
    Intended {
        state: "failed",
        reason: Some(reason),
    }
}

struct Pkg {
    name: String,
    cases: Vec<u32>,
    description: &'static str,
    display: DisplayState,
    offer_size: u64,
    content_length: Option<u64>,
    body: Vec<u8>,
    after: &'static str,
    intended: Intended,
}

/// A package case whose response is exactly `body`, offered at its own length.
fn pkg(
    name: impl Into<String>,
    cases: &[u32],
    description: &'static str,
    display: DisplayState,
    body: Vec<u8>,
    intended: Intended,
) -> Pkg {
    Pkg {
        name: name.into(),
        cases: cases.to_vec(),
        description,
        display,
        offer_size: body.len() as u64,
        content_length: Some(body.len() as u64),
        body,
        after: "ends",
        intended,
    }
}

