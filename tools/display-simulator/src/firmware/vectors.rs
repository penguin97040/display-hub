//! Conformance vectors for signed firmware updates (`protocol/v1/firmware/`): the display cases in
//! `docs/firmware-updates.md`, "What the simulator must test", as language-neutral files a display's
//! firmware ports to its own unit tests.
//!
//! Each vector names the public keys it uses, the display's state before, what arrives, and what the
//! display must do. Four kinds:
//!
//! - `package`: an offer and the download's response, through steps 1 to 9;
//! - `offer`: the attempt budget and the offer last acted on, through a series of events ("Limits on
//!   trying");
//! - `trial`: a trial boot's check-ins, and whether the new firmware is marked good or rolls back;
//! - `provision`: a provisioning bundle's firmware section, or a factory reset, and the keys after.
//!
//! `ring` signs with a random nonce, so packages can't be regenerated byte for byte. The vectors are
//! made once with throwaway keys (their private halves exist only while [`generate`] runs) and then
//! **checked**: [`check`] runs every committed file through this reference display, and [`stable`]
//! is what a fresh generation must agree with, everything except the keys and the package bytes.

