//! Prints the Unicode tables dh_core needs for its NFC check, as C source.
//!
//! Everything comes from the unicode-normalization crate at the version crates/hub-protocol pins,
//! so the display refuses exactly the text the hub refuses. Hangul is left out: dh_core composes
//! and decomposes it by arithmetic. No decomposition table is needed: see the check in `main`.

use unicode_normalization::char::{canonical_combining_class, compose, decompose_canonical};
use unicode_normalization::{is_nfc_quick, IsNormalized, UNICODE_VERSION};

const HANGUL_FIRST: u32 = 0xAC00;
const HANGUL_LAST: u32 = 0xD7A3;
const JAMO_L: std::ops::RangeInclusive<u32> = 0x1100..=0x1112;
const JAMO_V: std::ops::RangeInclusive<u32> = 0x1161..=0x1175;
const JAMO_T: std::ops::RangeInclusive<u32> = 0x11A8..=0x11C2;

fn is_hangul(c: u32) -> bool {
    (HANGUL_FIRST..=HANGUL_LAST).contains(&c)
}

fn chars() -> impl Iterator<Item = char> {
    (0..=0x10FFFFu32).filter_map(char::from_u32)
}

/// Runs of code points that share a non-zero value, as (first, last, value).
fn ranges(value: impl Fn(char) -> u8) -> Vec<(u32, u32, u8)> {
    let mut out: Vec<(u32, u32, u8)> = Vec::new();
    for c in chars() {
        let v = value(c);
        if v == 0 {
            continue;
        }
        let cp = c as u32;
        match out.last_mut() {
            Some(last) if last.1 + 1 == cp && last.2 == v => last.1 = cp,
            _ => out.push((cp, cp, v)),
        }
    }
    out
}

fn main() {
    let (ma, mi, pa) = UNICODE_VERSION;
    println!("/* Generated by tools/unicode-tables from unicode-normalization 0.1.26");
    println!(" * (Unicode {ma}.{mi}.{pa}). Do not edit: change the generator and run it again. */");
    println!();
    println!("#include \"dh_unicode_tables.h\"");
    println!();

    let ccc = ranges(canonical_combining_class);
    println!("const uint32_t dh_ccc_ranges[][2] = {{");
    for (f, l, v) in &ccc {
        println!("    {{0x{:06X}u | ({v}u << 24), 0x{l:06X}u}},", f);
    }
    println!("}};");
    println!("const size_t dh_ccc_range_count = {};", ccc.len());
    println!();

    // Quick check, character by character: 1 for No, 2 for Maybe. Hangul jamo V and T are Maybe
    // and stay in the table; the syllables themselves are Yes.
    let qc = ranges(|c| match is_nfc_quick(std::iter::once(c)) {
        IsNormalized::Yes => 0,
        IsNormalized::No => 1,
        IsNormalized::Maybe => 2,
    });
    println!("const uint32_t dh_nfc_qc_ranges[][2] = {{");
    for (f, l, v) in &qc {
        println!("    {{0x{:06X}u | ({v}u << 24), 0x{l:06X}u}},", f);
    }
    println!("}};");
    println!("const size_t dh_nfc_qc_range_count = {};", qc.len());
    println!();

    // Primary composites: every pair (a, b) that composes, outside Hangul. Only a character whose
    // quick check is Maybe can be the second of a pair, so that bounds the search.
    let seconds: Vec<char> = chars()
        .filter(|&c| is_nfc_quick(std::iter::once(c)) == IsNormalized::Maybe)
        .filter(|&c| !JAMO_V.contains(&(c as u32)) && !JAMO_T.contains(&(c as u32)))
        .collect();
    let mut pairs = Vec::new();
    for a in chars() {
        let ac = a as u32;
        if is_hangul(ac) || JAMO_L.contains(&ac) {
            continue;
        }
        for &b in &seconds {
            if let Some(c) = compose(a, b) {
                pairs.push((ac, b as u32, c as u32));
            }
        }
    }
    // Make sure nothing composes with a second outside that set.
    for a in chars().step_by(97) {
        for b in chars().step_by(89) {
            if !seconds.contains(&b) && !is_hangul(a as u32) && !JAMO_L.contains(&(a as u32)) {
                assert!(compose(a, b).is_none(), "{:X} {:X}", a as u32, b as u32);
            }
        }
    }
    pairs.sort();

    // A text that passes the quick check holds no character whose quick check is No, so every
    // character in it that decomposes at all is a primary composite, and its decomposition is its
    // pair, applied again to the pair's first character. Check that this rebuilds the crate's own
    // full decomposition for every such character.
    let decompose_by_pairs = |c: u32| -> Vec<u32> {
        let mut out = vec![c];
        loop {
            let first = out[0];
            if is_hangul(first) {
                let s = first - HANGUL_FIRST;
                let (l, v, t) = (0x1100 + s / 588, 0x1161 + (s % 588) / 28, s % 28);
                let mut d = vec![l, v];
                if t != 0 {
                    d.push(0x11A7 + t);
                }
                out.splice(0..1, d);
                break;
            }
            match pairs.iter().find(|p| p.2 == first) {
                Some(&(a, b, _)) => {
                    out.splice(0..1, [a, b]);
                }
                None => break,
            }
        }
        out
    };
    for c in chars() {
        if is_nfc_quick(std::iter::once(c)) == IsNormalized::No {
            continue;
        }
        let mut want = Vec::new();
        decompose_canonical(c, |x| want.push(x as u32));
        assert_eq!(decompose_by_pairs(c as u32), want, "{:X}", c as u32);
        // dh_core checks NFC one segment at a time, starting a segment at each character whose
        // quick check is Yes and whose class is 0. That is exact only if such a character's
        // decomposition starts with one too, so nothing after it can reach back past it.
        if is_nfc_quick(std::iter::once(c)) == IsNormalized::Yes && canonical_combining_class(c) == 0 {
            let first = char::from_u32(want[0]).expect("a character");
            assert_eq!(
                is_nfc_quick(std::iter::once(first)),
                IsNormalized::Yes,
                "{:X}",
                c as u32
            );
            assert_eq!(canonical_combining_class(first), 0, "{:X}", c as u32);
        }
    }
    println!("/* (first << 42) | (second << 21) | composite, sorted. */");
    println!("const uint64_t dh_compose_pairs[] = {{");
    for (a, b, c) in &pairs {
        println!("    (0x{a:06X}ull << 42) | (0x{b:06X}ull << 21) | 0x{c:06X}ull,");
    }
    println!("}};");
    println!("const size_t dh_compose_count = {};", pairs.len());
    println!();

    // The same pairs by composite, for decomposing.
    let mut by_composite: Vec<usize> = (0..pairs.len()).collect();
    by_composite.sort_by_key(|&i| pairs[i].2);
    println!("/* Indexes into dh_compose_pairs, sorted by composite. */");
    println!("const uint16_t dh_compose_by_composite[] = {{");
    for chunk in by_composite.chunks(12) {
        let s: Vec<String> = chunk.iter().map(|i| format!("{i}")).collect();
        println!("    {},", s.join(", "));
    }
    println!("}};");
}
